import { esc } from './theme.mjs';

const REDUCED = '(prefers-reduced-motion: reduce)';
const DARK = '(prefers-color-scheme: dark)';

const source = (media, url) => `<source media="${media}" srcset="${url}">`;

// A media query inside an image can't see the reader's reduced-motion setting, so the choice has
// to happen here: readers who asked for no motion get a still copy of anything animated.
function picture(raw, name, alt, attrs, { animated = false } = {}) {
  const stills = animated
    ? source(`${REDUCED} and ${DARK}`, `${raw}/${name}-dark-still.svg`) + source(REDUCED, `${raw}/${name}-light-still.svg`)
    : '';
  return `<picture>${stills}${source(DARK, `${raw}/${name}-dark.svg`)}<img alt="${esc(alt)}" src="${raw}/${name}-light.svg" ${attrs}></picture>`;
}

const linked = (href, inner) => `<a href="${esc(href)}">${inner}</a>`;
const small = (s) => `<small>${s}</small>`;
const WIDE = 'width="100%"';

// Socials, the banner, who you are, the team. GitHub allows no styles in a README, so body text
// sits in <small>, a step below the default size, under an h2.
export function readme({ profile, team, socials, raw, alts }) {
  const animated = { animated: true };
  const pills = socials.map((s) => linked(s.href, picture(raw, `social-${s.key}`, s.alt, 'height="32"'))).join('\n');
  const sections = Object.entries(profile.sections)
    .map(([title, items]) => `#### ${title}\n\n${items.map((item) => `- ${small(item)}`).join('\n')}`)
    .join('\n\n');
  const slices = team
    .map((m, i) => linked(m.href, picture(raw, `team-${i + 1}`, `${m.name}, ${m.role}`, `width="${100 / team.length}%"`, animated)))
    .join('');
  return [
    '<!-- Generated by .wt/render.mjs from profile.json. Edit profile.json, not this file. -->',
    `<p>${pills}</p>`,
    `<p>${picture(raw, 'hero', alts.hero, WIDE, animated)}</p>`,
    `## Hey, I'm ${profile.name} 👋`,
    profile.intro.map(small).join('\n\n'),
    `<p>${picture(raw, 'pillars', alts.pillars, WIDE, animated)}</p>`,
    sections,
    `<p>${picture(raw, 'marquee', alts.marquee, WIDE, animated)}</p>`,
    `<p>${linked(profile.cta.href, picture(raw, 'cta', profile.cta.label, 'height="32"', animated))}</p>`,
    `<p>${slices}</p>`,
  ].join('\n\n') + '\n';
}
